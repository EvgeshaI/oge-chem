/**
 * Итоговая игра «Химическое расследование»: обобщение тем курса.
 * 5 дел по 4 улики. Каждая улика — вопрос из одной темы; у каждой есть «нюанс»,
 * по ним в конце строится разбор «на что обратить внимание».
 */

export type QuestTopic = 'concepts' | 'atom' | 'periodic' | 'oxidation' | 'bonds'

export interface Nuance {
  topic: QuestTopic
  title: string
  /** Краткое правило — показывается как подсказка после ошибки и в итогах */
  tip: string
  /** Где повторить: название пункта теории в теме */
  lesson: string
}

export interface QuestStep {
  id: string
  topic: QuestTopic
  nuance: string
  /** Сюжетная подводка */
  story: string
  question: string
  kind: 'single' | 'digits'
  options: string[]
  /** single — номер варианта с 1; digits — цифры верных вариантов (по возрастанию) */
  answer: number | string
  explanation: string
  /** Что узнали — попадает в «блокнот» детектива */
  found: string
  /** Цифра кода сейфа, которую открывает эта улика (для дела с сейфом) */
  code?: string
}

export interface QuestCase {
  id: string
  title: string
  emoji: string
  intro: string
  outro: string
  steps: QuestStep[]
}

