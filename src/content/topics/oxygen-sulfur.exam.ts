const d = (n: number, question: string, options: string[], answer: string, explanation: string): DigitsTask => ({
  id: `oxygen-sulfur.e${n}`,
  type: 'digits',
  question: `${question} Запишите номера выбранных ответов.`,
  options,
  answer,
  explanation,
})

const m = (n: number, q: string, hint: string, rows: string[], choices: string[], answer: string, explanation: string): MatchTask => ({
  id: `oxygen-sulfur.e${n}`,
  type: 'match',
  question: q,
  rows,
  choices,
  answer,
  hint,
  explanation,
})

