const d = (n: number, question: string, options: string[], answer: string, explanation: string): DigitsTask => ({
  id: `halogens.e${n}`,
  type: 'digits',
  question: `${question} Запишите номера выбранных ответов.`,
  options,
  answer,
  explanation,
})

const o = (n: number, question: string, options: string[], answer: string, explanation: string): OrderTask => ({
  id: `halogens.e${n}`,
  type: 'order',
  question: `${question} Запишите номера в соответствующем порядке.`,
  options,
  answer,
  explanation,
})

const s = (n: number, question: string, options: string[], answer: number, explanation: string): SingleTask => ({
  id: `halogens.e${n}`,
  type: 'single',
  question,
  options,
  answer,
  explanation,
})

const m = (n: number, q: string, hint: string, rows: string[], choices: string[], answer: string, explanation: string): MatchTask => ({
  id: `halogens.e${n}`,
  type: 'match',
  question: q,
  rows,
  choices,
  answer,
  hint,
  explanation,
})

