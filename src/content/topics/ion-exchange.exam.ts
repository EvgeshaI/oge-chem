const f = (s: string) => `$\\ce{${s}}$`
const pair = (a: string, b: string) => `${f(a)} и ${f(b)}`

const HINT = 'Для каждой буквы выберите цифру. Цифры в ответе могут повторяться.'

const d = (n: number, question: string, options: string[], answer: string, explanation: string): DigitsTask => ({
  id: `ion-exchange.e${n}`,
  type: 'digits',
  question: `${question} Запишите номера выбранных ответов.`,
  options,
  answer,
  explanation,
})

const m = (n: number, q: string, rows: string[], choices: string[], answer: string, explanation: string): MatchTask => ({
  id: `ion-exchange.e${n}`,
  type: 'match',
  question: q,
  rows,
  choices,
  answer,
  hint: HINT,
  explanation,
})

const s = (n: number, question: string, options: string[], answer: number, explanation: string): SingleTask => ({
  id: `ion-exchange.e${n}`,
  type: 'single',
  question,
  options,
  answer,
  explanation,
})

