/** Урок с разбором задачи: условие и пошаговая анимация, затем оформление «как на экзамене» */
function problemLesson(
  n: 1 | 2 | 3 | 4 | 5,
  title: string,
  intro: string,
  solution: { title: string; text: string }[],
  warn: string,
): Lesson {
  const p = PROBLEMS[n - 1]
  const blocks: Block[] = [
    { kind: 'callout', tone: 'remember', title: 'Условие', text: p.condition },
    { kind: 'text', text: intro },
    { kind: 'animation', name: `problem-chain-${n}` as AnimationName },
    { kind: 'heading', text: 'Как записать решение' },
    { kind: 'steps', vertical: true, items: solution },
    { kind: 'callout', tone: 'tip', title: 'Ответ', text: `**${p.answer}**.` },
    { kind: 'callout', tone: 'warn', text: warn },
  ]
  return { id: `problem-solving.task${n}`, title: `Задача ${n}. ${title}`, blocks }
}

