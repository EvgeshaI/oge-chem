/** Цветная формула из кусочков */
const S = (segs: Seg[], coef = 1) => `$${itemsTex([{ id: 'x', coef, segs }])}$`
const cat = (t: string): Seg => [t, 'cat']
const an = (t: string): Seg => [t, 'an']
const k = (t: string): Seg => [t, 'k']

/** Три вида уравнения для одной реакции из данных */
function forms(id: string) {
  const r = reactionById(id)
  const mol = { l: sideItems(r.left, 'L', false), r: sideItems(r.right, 'R', false) }
  const full = { l: sideItems(r.left, 'L', true), r: sideItems(r.right, 'R', true) }
  return {
    mol: equationTex(mol.l, mol.r),
    full: equationTex(full.l, full.r),
    short: equationTex(shortItems(full.l), shortItems(full.r)),
  }
}

const threeForms = (id: string): Block => {
  const t = forms(id)
  return {
    kind: 'table',
    head: ['Вид уравнения', 'Запись'],
    rows: [
      ['**Молекулярное**', `$${t.mol}$`],
      ['**Полное ионное**', `$${t.full}$`],
      ['**Сокращённое ионное**', `$${t.short}$`],
    ],
    cellColors: [
      [HEAD, null],
      [HEAD, null],
      [GREEN, null],
    ],
  }
}

