import type { Cell, Task } from '../types'

// Задачи по теме «Массовая доля»: 20 расчётных заданий, ответ вписывается числом в поле.
// В каждом условии указано, до какого разряда округлять. Ar: H 1, C 12, N 14, O 16, Na 23, Mg 24, Al 27,
// S 32, Cl 35,5, K 39, Ca 40, Fe 56.

const f = (s: string) => `$\\ce{${s}}$`
const input = (a: string, w = 8): Cell => ({ a, w })

const ROUND = (r: string) => `Ответ округлите до ${r}.`
const HINT =
  'Впишите только число, без единиц измерения. Дробную часть можно писать через запятую или точку. Округляйте только в самом конце расчёта.'

interface T {
  n: number
  question: string
  unit: '%' | 'г'
  answer: string
  explanation: string
}

const task = (t: T): Task => ({
  id: `mass-fraction.p${t.n}`,
  type: 'cells',
  question: t.question,
  hint: HINT,
  head: [`Ответ, ${t.unit}`],
  rows: [[input(t.answer)]],
  explanation: t.explanation,
})

const ELEMENT = (n: number, formula: string, _el: string, name: string, answer: string, digits: string, solution: string): Task =>
  task({
    n,
    question: `Вычислите массовую долю ${name} в веществе ${f(formula)}. ${ROUND(digits)} Ответ запишите в процентах.`,
    unit: '%',
    answer,
    explanation: `${solution} Ответ: **${answer}%**.`,
  })

