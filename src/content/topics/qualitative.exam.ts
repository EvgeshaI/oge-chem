const f = (s: string) => `$\\ce{${s}}$`
const pair = (a: string, b: string) => `${f(a)} и ${f(b)}`
const LETTERS = 'к каждой позиции, обозначенной буквой, подберите соответствующую позицию, обозначенную цифрой.'
const QREAGENT = `Установите соответствие между двумя веществами и реактивом, с помощью которого можно различить эти вещества: ${LETTERS}`

const s = (n: number, question: string, options: string[], answer: number, explanation: string): SingleTask => ({
  id: `qualitative.e${n}`,
  type: 'single',
  question,
  options,
  answer,
  explanation,
})

const d = (n: number, question: string, options: string[], answer: string, explanation: string): DigitsTask => ({
  id: `qualitative.e${n}`,
  type: 'digits',
  question: `${question} Запишите номера выбранных ответов.`,
  options,
  answer,
  explanation,
})

const m = (n: number, question: string, rows: string[], choices: string[], answer: string, explanation: string): MatchTask => ({
  id: `qualitative.e${n}`,
  type: 'match',
  question,
  rows,
  choices,
  answer,
  explanation,
})

