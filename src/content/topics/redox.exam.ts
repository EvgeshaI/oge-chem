// Формат ОГЭ по теме «Окислительно-восстановительные реакции».
// Вариант 1 — тесты части 1; вариант 2 — задания части 2 (уравнение без коэффициентов,
// окислитель и восстановитель, электронный баланс).

const f = (s: string) => `$\\ce{${s}}$`

const d = (n: number, question: string, options: string[], answer: string, explanation: string): DigitsTask => ({
  id: `redox.e${n}`,
  type: 'digits',
  question: `${question} Запишите номера выбранных ответов.`,
  options,
  answer,
  explanation,
})
const m = (n: number, question: string, rows: string[], choices: string[], answer: string, explanation: string): MatchTask => ({
  id: `redox.e${n}`,
  type: 'match',
  question,
  rows,
  choices,
  answer,
  hint: 'Для каждой буквы выберите цифру. Цифры в ответе могут повторяться.',
  explanation,
})
const s = (n: number, question: string, options: string[], answer: number, explanation: string): SingleTask => ({
  id: `redox.e${n}`,
  type: 'single',
  question,
  options,
  answer,
  explanation,
})

const SUB = '₀₁₂₃₄₅₆₇₈₉'
const name = (ce: string) => ce.replace(/\d/g, (c) => SUB[+c])

const part2 = (
  n: number,
  p: {
    ce: string[]
    nLeft: number
    coef: number[]
    ox: number
    red: number
    halfRed: RedoxTask['halfRed']
    halfOx: RedoxTask['halfOx']
    note?: string
    explanation: string
  },
): RedoxTask => ({
  id: `redox.e${n}`,
  type: 'redox',
  question: `Используя метод электронного баланса, составьте уравнение реакции${p.note ? ` (${p.note})` : ''}: ${f(
    `${p.ce.slice(0, p.nLeft).join(' + ')} -> ${p.ce.slice(p.nLeft).join(' + ')}`,
  )}. Расставьте коэффициенты, определите окислитель и восстановитель.`,
  ce: p.ce,
  nLeft: p.nLeft,
  coef: p.coef,
  names: p.ce.map(name),
  ox: p.ox,
  red: p.red,
  halfRed: p.halfRed,
  halfOx: p.halfOx,
  explanation: p.explanation,
})

