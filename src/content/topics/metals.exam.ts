const f = (s: string) => `$\\ce{${s}}$`

const HINT9 =
  'Для каждой буквы выберите цифру. Сначала решите, идёт ли реакция, затем определите продукты и степень окисления металла. Цифры в ответе могут повторяться.'
const HINT10 =
  'Для каждого вещества выберите пару реагентов: подходит только та пара, где реагируют **оба** вещества. Одно «нет» — пара не подходит.'

const d = (n: number, question: string, options: string[], answer: string, explanation: string): DigitsTask => ({
  id: `metals.e${n}`,
  type: 'digits',
  question: `${question} Запишите номера выбранных ответов.`,
  options,
  answer,
  explanation,
})

const Q9 =
  'Установите соответствие между реагирующими веществами и продуктом(-ами) их взаимодействия: к каждой позиции, обозначенной буквой, подберите соответствующую позицию, обозначенную цифрой.'
const Q10 =
  'Установите соответствие между веществом и реагентами, с каждым из которых это вещество может вступать в реакцию: к каждой позиции, обозначенной буквой, подберите соответствующую позицию, обозначенную цифрой.'

const m9 = (n: number, rows: string[], choices: string[], answer: string, explanation: string): MatchTask => ({
  id: `metals.e${n}`,
  type: 'match',
  question: Q9,
  rows,
  choices,
  answer,
  hint: HINT9,
  explanation,
})

const m10 = (n: number, rows: string[], choices: string[], answer: string, explanation: string): MatchTask => ({
  id: `metals.e${n}`,
  type: 'match',
  question: Q10,
  rows,
  choices,
  answer,
  hint: HINT10,
  explanation,
})

