/**
 * Механизмы реакций металлов: что на что меняется (покадровые сцены).
 * Каждая сцена — несколько шагов; частицы с одинаковым id плавно «перетекают» из шага в шаг:
 * атом → ион, молекула → атомы → продукт. Электроны показываются отдельно (перелёты).
 */

export type Kind = 'metal' | 'cu' | 'ag' | 'cation' | 'anion' | 'cl' | 'o' | 's' | 'h' | 'hplus' | 'c'

export type GroupId = 'nonmetals' | 'water' | 'acids' | 'salts' | 'oxides'

export interface St {
  x: number
  y: number
  /** подпись внутри частицы */
  t: string
  k: Kind
  /** степень окисления (бейдж над частицей) */
  ox?: string
  r?: number
}

/** Перелёт электронов от одной частицы к другой */
export interface Flight {
  from: string
  to: string
  n: number
}

export interface Note {
  x: number
  y: number
  /** строки разделяются \n */
  t: string
  tone?: 'info' | 'good' | 'bad'
}

export interface Step {
  title: string
  text: string
  sp: Record<string, St>
  e?: Flight[]
  notes?: Note[]
  /** цвет раствора на этом шаге */
  tint?: string
  /** частицы, которые «трясутся» (реакции нет) */
  shake?: string[]
}

export interface Role {
  el: string
  from: string
  to: string
  change: string
  role: 'восстановитель' | 'окислитель'
}

export interface Scene {
  id: string
  group: GroupId
  /** текст кнопки */
  tab: string
  /** уравнение в формате mhchem (без \ce) или готовый TeX, если raw */
  eq: string
  /** сколько электронов передаётся в сумме (0 — реакции нет) */
  electrons: number
  solution?: string
  steps: Step[]
  roles: Role[]
}

