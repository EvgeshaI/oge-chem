/**
 * Механизмы реакций углерода и кремния: покадровые сцены для движка ReactionMechanism.
 * Правила те же, что в mechanisms.ts: частицы с одним id плавно перетекают из шага в шаг,
 * электроны показываются перелётами (на втором шаге), над частицей — степень окисления.
 */
import { a, next, type GroupId, type Kind, type Scene } from './mechanisms'

export type CsGroup = Extract<GroupId, 'cs-carbon' | 'cs-silicon'>

/* ---------------------------------------------------------------- C / Si + O₂ → CO₂ / SiO₂ */

function burn(o: { id: string; group: CsGroup; el: 'C' | 'Si'; kind: Kind; eq: string; tab: string; product: string; text0: string; text2: string; footnote: string; note: string }): Scene {
  const s0 = {
    x: a(110, 130, o.el, o.kind, '0'),
    o1: a(420, 130, 'O', 'o', '0'),
    o2: a(456, 130, 'O', 'o', '0'),
  }
  const s1 = next(s0, { x: { x: 320 }, o1: { x: 200 }, o2: { x: 440 } })
  const s2 = next(s1, {
    x: { ox: '+4' },
    o1: { x: o.el === 'C' ? 264 : 258, ox: '−2' },
    o2: { x: o.el === 'C' ? 376 : 382, ox: '−2' },
  })
  return {
    id: o.id,
    group: o.group,
    tab: o.tab,
    eq: o.eq,
    electrons: 4,
    footnote: o.footnote,
    roles: [
      { el: o.el, from: '0', to: '+4', change: 'пары смещаются от атома (4ē)', role: 'восстановитель' },
      { el: 'O', from: '0', to: '−2', change: 'принимает 2ē', role: 'окислитель' },
    ],
    steps: [
      {
        title: 'Было',
        text: o.text0,
        sp: s0,
        notes: [
          { x: 110, y: 186, t: o.el === 'C' ? 'атом углерода' : 'атом кремния' },
          { x: 438, y: 178, t: 'молекула O₂' },
        ],
      },
      {
        title: 'Пары смещаются к кислороду',
        text: `Молекула кислорода распадается на атомы. ${o.el === 'C' ? 'Углерод' : 'Кремний'} своими **четырьмя** внешними электронами образует по две общие пары с каждым атомом кислорода. Кислород электроотрицательнее — пары **смещаются к кислороду**.`,
        sp: s1,
        e: [
          { from: 'x', to: 'o1', n: 2 },
          { from: 'x', to: 'o2', n: 2 },
        ],
        notes: [{ x: 320, y: 200, t: `${o.el} «отдаёт» 4ē`, tone: 'info' }],
      },
      {
        title: o.product,
        text: o.text2,
        sp: s2,
        notes: [{ x: 320, y: 200, t: o.note, tone: 'good' }],
      },
    ],
  }
}

