/* ---------------------------------------------------------------- металл + неметалл (Э³⁻): Mg₃N₂, Ca₃P₂ */

function metalNitride(o: { id: string; group: PnGroup; m: 'Mg' | 'Ca'; x: 'N' | 'P'; kind: Kind; eq: string; name: string; cond: string; footnote: string; product: string }): Scene {
  const X = o.x
  const s0 = {
    m1: a(100, 52, o.m, 'metal', '0'),
    m2: a(100, 122, o.m, 'metal', '0'),
    m3: a(100, 192, o.m, 'metal', '0'),
    x1: X === 'N' ? a(430, 130, 'N', o.kind, '0') : a(430, 80, 'P', o.kind, '0'),
    x2: X === 'N' ? a(466, 130, 'N', o.kind, '0') : a(430, 190, 'P', o.kind, '0'),
  }
  const s1 = next(s0, { x1: { x: 420, y: 80 }, x2: { x: 420, y: 190 } })
  const s2 = next(s1, {
    m1: { t: `${o.m}²⁺`, k: 'cation', ox: '+2' },
    m2: { t: `${o.m}²⁺`, k: 'cation', ox: '+2' },
    m3: { t: `${o.m}²⁺`, k: 'cation', ox: '+2' },
    x1: { t: `${X}³⁻`, k: 'anion', ox: '−3' },
    x2: { t: `${X}³⁻`, k: 'anion', ox: '−3' },
  })
  const s3 = next(s2, {
    m1: { x: 220, y: 80 },
    m2: { x: 350, y: 80 },
    m3: { x: 480, y: 80 },
    x1: { x: 285, y: 160 },
    x2: { x: 415, y: 160 },
  })
  const ion = X === 'N' ? 'нитрид-ион' : 'фосфид-ион'
  return {
    id: o.id,
    group: o.group,
    tab: `${o.m} + ${X === 'N' ? 'N₂' : 'P'}`,
    eq: o.eq,
    electrons: 6,
    footnote: o.footnote,
    roles: [
      { el: o.m, from: '0', to: '+2', change: 'отдаёт 2ē', role: 'восстановитель' },
      { el: X, from: '0', to: '−3', change: 'принимает 3ē', role: 'окислитель' },
    ],
    steps: [
      {
        title: 'Было',
        text: `Три атома ${o.m === 'Mg' ? 'магния' : 'кальция'} и ${X === 'N' ? 'молекула азота $\\ce{N2}$' : 'два атома фосфора'}. Степени окисления простых веществ — **0**. Реакция идёт ${o.cond}.`,
        sp: s0,
        notes: [
          { x: 100, y: 236, t: `атомы ${o.m}` },
          { x: X === 'N' ? 448 : 430, y: X === 'N' ? 178 : 236, t: X === 'N' ? 'молекула N₂' : 'атомы P' },
        ],
      },
      {
        title: 'Электроны переходят',
        text: `Каждый атом ${o.m === 'Mg' ? 'магния' : 'кальция'} отдаёт **2** электрона, каждый атом ${X === 'N' ? 'азота' : 'фосфора'} принимает **3** — до восьми ему не хватает трёх. Чтобы числа сошлись, нужно 3 атома металла на 2 атома ${X === 'N' ? 'азота' : 'фосфора'}: 3 · 2 = 2 · 3 = 6 электронов.`,
        sp: s1,
        e: [
          { from: 'm1', to: 'x1', n: 2 },
          { from: 'm2', to: 'x1', n: 1 },
          { from: 'm2', to: 'x2', n: 1 },
          { from: 'm3', to: 'x2', n: 2 },
        ],
        notes: [{ x: 280, y: 236, t: '3 · 2ē = 2 · 3ē', tone: 'info' }],
      },
      {
        title: 'Появились ионы',
        text: `Металл стал катионом $\\ce{${o.m}^2+}$ (+2), ${X === 'N' ? 'азот' : 'фосфор'} — анионом $\\ce{${X}^3-}$ (−3), это ${ion}. Внешний слой у всех ионов завершён.`,
        sp: s2,
      },
      {
        title: o.name,
        text: `Ионы притягиваются — образуется ${o.name.toLowerCase()} $\\ce{${o.product}}$ с **ионной** связью.`,
        sp: s3,
        notes: [{ x: 350, y: 230, t: `${o.product.replace(/(\d)/g, (d) => '₀₁₂₃₄₅₆₇₈₉'[Number(d)])} — ${o.name.toLowerCase()}`, tone: 'good' }],
      },
    ],
  }
}

