/** Атомы металлов ОГЭ: строение и электроны, которые они отдают (для анимации «атом → ион») */
export interface MetalAtom {
  id: string
  sym: string
  /** подпись на кнопке */
  chip: string
  name: string
  /** заряд ядра = число протонов = число электронов в атоме */
  z: number
  /** электроны по слоям в атоме */
  sh: number[]
  /** сколько электронов уходит с каждого слоя (длина = sh.length) */
  take: number[]
  /** пояснение, откуда уходят электроны */
  hint: string
}

