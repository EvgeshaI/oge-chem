export const chargeOf = (m: MetalAtom) => m.take.reduce((a, b) => a + b, 0)

const SUP = '⁰¹²³⁴⁵⁶⁷⁸⁹'
/** Mg²⁺, Na⁺ … */
export const ionLabel = (sym: string, charge: number) => `${sym}${charge > 1 ? SUP[charge] : ''}⁺`
