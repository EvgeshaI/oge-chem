interface DisplaceOpts {
  id: string
  tab: string
  eq: string
  /** вытесняющий галоген */
  h: { sym: string; kind: Kind; r: number }
  /** вытесняемый */
  p: { sym: string; kind: Kind; r: number }
  tintEnd: string
  obs: string
  /** «жёлтый» / «бурый» — как называется окраска */
  color: string
}

function displace(o: DisplaceOpts): Scene {
  const gap = o.h.r * 2 + 4
  const pgap = o.p.r * 2 + 2
  const s0: Record<string, St> = {
    h1: a(70, 100, o.h.sym, o.h.kind, '0', o.h.r),
    h2: a(70 + gap, 100, o.h.sym, o.h.kind, '0', o.h.r),
    k1: a(255, 70, 'K⁺', 'cation', '+1'),
    k2: a(255, 190, 'K⁺', 'cation', '+1'),
    p1: a(400, 70, o.p.sym + '⁻', 'anion', '−1'),
    p2: a(400, 190, o.p.sym + '⁻', 'anion', '−1'),
  }
  const s2 = next(s0, {
    h1: { t: o.h.sym + '⁻', k: 'anion', ox: '−1', r: undefined },
    h2: { t: o.h.sym + '⁻', k: 'anion', ox: '−1', r: undefined },
    p1: { t: o.p.sym, k: o.p.kind, ox: '0', r: o.p.r },
    p2: { t: o.p.sym, k: o.p.kind, ox: '0', r: o.p.r },
  })
  const s3 = next(s2, {
    h1: { x: 205, y: 70 },
    h2: { x: 205, y: 190 },
    p1: { x: 500, y: 130 },
    p2: { x: 500 + pgap, y: 130 },
  })
  return {
    id: o.id,
    group: 'hal-displace',
    tab: o.tab,
    eq: o.eq,
    electrons: 2,
    solution: 'раствор соли',
    footnote: 'Более активный галоген **принимает** электроны (окислитель), а ион менее активного галогена их **отдаёт** (восстановитель).',
    roles: [
      { el: o.p.sym + ' (в соли)', from: '−1', to: '0', change: 'отдаёт 1ē', role: 'восстановитель' },
      { el: o.h.sym, from: '0', to: '−1', change: 'принимает 1ē', role: 'окислитель' },
    ],
    steps: [
      {
        title: 'Было',
        text: `В растворе соли — ионы $\\ce{K+}$ и $\\ce{${o.p.sym}-}$. К нему добавили молекулу $\\ce{${o.h.sym}2}$ (показаны два атома).`,
        sp: s0,
        tint: CLEAR,
        notes: [
          { x: 70 + gap / 2, y: 150, t: `молекула ${o.h.sym}₂` },
          { x: 400, y: 130, t: `ионы ${o.p.sym}⁻` },
        ],
      },
      {
        title: 'Электроны переходят',
        text: `${o.h.sym} — более сильный окислитель. Он отнимает у ионов $\\ce{${o.p.sym}-}$ по электрону.`,
        sp: s0,
        tint: CLEAR,
        e: [
          { from: 'p1', to: 'h1', n: 1 },
          { from: 'p2', to: 'h2', n: 1 },
        ],
        notes: [{ x: 240, y: 130, t: 'электроны уходят\nк более активному галогену', tone: 'info' }],
      },
      {
        title: 'Что получилось',
        text: `${o.h.sym} стал ионом $\\ce{${o.h.sym}-}$ (−1). Ионы $\\ce{${o.p.sym}-}$, отдав электроны, стали **атомами** ${o.p.sym} (степень окисления 0). Раствор начинает менять цвет.`,
        sp: s2,
        tint: o.tintEnd,
      },
      {
        title: 'Новый галоген выделился',
        text: `Атомы ${o.p.sym} соединяются в молекулу $\\ce{${o.p.sym}2}$ — это и есть вытесненный галоген. В растворе остались $\\ce{K+}$ и $\\ce{${o.h.sym}-}$ — соль $\\ce{K${o.h.sym}}$. **${o.obs}**`,
        sp: s3,
        tint: o.tintEnd,
        notes: [
          { x: 230, y: 130, t: `K${o.h.sym} в растворе`, tone: 'good' },
          { x: 500 + pgap / 2, y: 190, t: `${o.p.sym}₂ — ${o.color}`, tone: 'good' },
        ],
      },
    ],
  }
}

